namespace CropDeal.Controllers;

[Authorize(Roles = "Admin")]
[ApiController]
[Route("api/[controller]")]
public class ReportController : ControllerBase
{
    private readonly IReportRepository _reportRepo;
    private readonly CropDealDBContext _context;

    public ReportController(IReportRepository reportRepo, CropDealDBContext context)
    {
        _reportRepo = reportRepo;
        _context = context;
    }

    [HttpPost("Admin/GenerateReport/{dealerId}")]
    public async Task<IActionResult> GenerateReport(Guid dealerId, [FromBody] string filter = null)
    {
        var adminIdClaim = User.FindFirst(ClaimTypes.NameIdentifier);
        if (adminIdClaim == null)
        {
            return Unauthorized("Admin ID not found.");
        }
        var adminId = Guid.Parse(adminIdClaim.Value);
        var report = await _reportRepo.GenerateDealerReportAsync(adminId, dealerId);
        return Ok(report);
    }

    [HttpGet("Admin/GetAllReports")]
    public async Task<IActionResult> GetAll()
    {
        var reports = await _reportRepo.GetAllAsync();
        if (reports != null)
        {
            return Ok(reports);
        }
        return BadRequest();
    }

    [HttpGet("Admin/GetReportById/{id}")]
    public async Task<IActionResult> GetById(Guid id)
    {
        var report = await _reportRepo.GetByIdAsync(id);
        if (report == null)
        {
            return NotFound();
        }
        return Ok(report);
    }

